"""The compose stack of a node: one part (or more) per app, one generated root.

On the node the stack is /opt/compose/compose.yml, which includes every part in
/opt/compose/compose.d/. The root is generated from node.yml — the project name
and the apps in their order — so adding an app is one entry there and nothing
else.
"""

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

import yaml

from . import log
from .config import App, Node
from .errors import BuildError, ConfigError

COMPOSE_DIR = "/opt/compose"


def parts(node: Node, apps=None) -> list:
    """[(app, source path)] in stack order, for all apps or the ones named."""
    out = []
    for app in node.apps:
        if apps is None or app.name in apps:
            out.extend((app, p) for p in app.compose)
    return out


def check_part_names(node: Node) -> None:
    seen = {}
    for app, p in parts(node):
        if p.name in seen:
            raise ConfigError(app.where, f"node {node.name}: compose file name {p.name} is used by app "
                                         f"{seen[p.name]} and app {app.name}; they share compose.d/, so "
                                         "the names have to differ")
        seen[p.name] = app.name


def root_yaml(node: Node) -> str:
    lines = [
        "# Generated by Flatcar Builder from node.yml — edit that, not this.",
        f"name: {node.project}",
        "include:",
    ]
    lines += [f"  - compose.d/{p.name}" for _, p in parts(node)]
    if not node.apps:
        lines[-1] = "include: []"
    return "\n".join(lines) + "\n"


def _load_part(path: Path, node: Node) -> dict:
    try:
        data = yaml.safe_load(path.read_text())
    except yaml.YAMLError as e:
        raise ConfigError(str(path), f"node {node.name}: compose file is not valid YAML: {e}") from None
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ConfigError(str(path), f"node {node.name}: a compose file must be a mapping")
    return data


def services_in(path: Path, node: Node) -> dict:
    services = _load_part(path, node).get("services") or {}
    if not isinstance(services, dict):
        raise ConfigError(str(path), f"node {node.name}: 'services' must be a mapping")
    return services


def app_services(node: Node, app: App) -> list:
    out = []
    for p in app.compose:
        out.extend(services_in(p, node).keys())
    return out


def check_images(node: Node) -> None:
    """Every image: in an app's parts is one that app ships; an unused one is a warning.

    An image the part names but the app does not ship is a container that never
    starts on the node, because the node never reaches a registry.
    """
    for app in node.apps:
        shipped = {img.name for img in app.images}
        used = set()
        for p in app.compose:
            for svc, body in services_in(p, node).items():
                image = (body or {}).get("image") if isinstance(body, dict) else None
                if isinstance(body, dict) and "build" in body:
                    raise ConfigError(str(p), f"node {node.name}, service {svc}: 'build:' is not allowed; "
                                              "images are built on the build machine (see the app's images "
                                              "in node.yml) and shipped as tars")
                if not image:
                    continue
                used.add(image)
                if image not in shipped:
                    raise ConfigError(str(p), f"node {node.name}, app {app.name}: service {svc} uses image "
                                              f"{image!r}, which is not in the app's images — the tar will "
                                              "not reach the node")
        for img in app.images:
            if img.name not in used:
                log.warn(f"node {node.name}, app {app.name}: image {img.name} is shipped but no service of "
                         "the app uses it")


def write_stack(node: Node, dest: Path) -> None:
    """compose.yml + compose.d/ as they will be on the node."""
    (dest / "compose.d").mkdir(parents=True, exist_ok=True)
    (dest / "compose.yml").write_text(root_yaml(node))
    for _, p in parts(node):
        shutil.copyfile(p, dest / "compose.d" / p.name)


def compose_plugin_available() -> bool:
    if shutil.which("docker") is None:
        return False
    return subprocess.run(["docker", "compose", "version"], stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL).returncode == 0


def validate(node: Node, use_plugin=None) -> None:
    """Check the whole stack before it is shipped.

    The compose plugin checks the YAML, the schema and the include list as one
    merged model. Without it every file is at least parsed, with a warning that
    the schema was not checked.
    """
    check_part_names(node)
    if use_plugin is None:
        use_plugin = compose_plugin_available()
    for _, p in parts(node):
        _load_part(p, node)
    if not use_plugin:
        log.warn(f"node {node.name}: docker compose plugin not found — only the YAML syntax of the stack "
                 "was checked, not the compose schema")
        return
    with tempfile.TemporaryDirectory(prefix="fcb-compose-") as tmp:
        write_stack(node, Path(tmp))
        env = dict(os.environ, NODE_NAME=node.name, HOSTNAME=node.hostname)
        r = subprocess.run(["docker", "compose", "-f", "compose.yml", "config", "--quiet"],
                           cwd=tmp, env=env, capture_output=True, text=True)
        if r.returncode != 0:
            raise BuildError(f"node {node.name}: the compose stack is rejected by docker compose:\n"
                             f"{(r.stderr or r.stdout).strip()}")
